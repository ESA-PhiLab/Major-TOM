"""The products table of docs/ARCHIVES.md, generated from collections.py so the document cannot drift.

    COLLECTIONS  ->  one row per product: kind, bands, then per archive its period (or "—")
                 ->  written between the markers below in docs/ARCHIVES.md

    python -m majortom.build.catalogue            rewrite the table in docs/ARCHIVES.md
    python -m majortom.build.catalogue --check    exit 1 if the table is out of date (tests/test_catalogue.py)
"""
from __future__ import annotations

import sys
from pathlib import Path

from .archives import ARCHIVES
from .collections import COLLECTIONS

DOC = Path(__file__).resolve().parents[2] / "docs" / "ARCHIVES.md"
BEGIN = "<!-- products table: generated by python -m majortom.build.catalogue -->"
END = "<!-- end of products table -->"
KINDS = ["optical", "radar", "elevation", "land cover", "temperature", "night lights", "biomass", "water"]


def period(name: str, archive: str) -> str:
    """A source's time range as table text: "2015-06 –" (ongoing), "2000-03 – 2006-12", "static", or "—"."""
    collection = COLLECTIONS[name]
    source = collection.source(name, archive)
    if source is None:
        return "—"
    if source.period is None:
        return "static" if collection.time == "static" else "✓"
    start, end = source.period
    return f"{start[:7]} – {end[:7] if end else ''}".rstrip()


def cell(name: str, archive: str) -> str:
    """A table cell: the period, linked to the archive's page for that collection where it has one."""
    text, source = period(name, archive), COLLECTIONS[name].source(name, archive)
    page = ARCHIVES[archive].page
    return f"[{text}]({page(source.collection)})" if source and page else text


def table() -> str:
    """The Markdown products table."""
    archives = list(ARCHIVES)
    lines = ["| Product | Kind | Bands | " + " | ".join(archives) + " |",
             "|---|---|---|" + "---|" * len(archives)]
    for name in sorted(COLLECTIONS, key=lambda n: (KINDS.index(COLLECTIONS[n].kind), n)):
        c = COLLECTIONS[name]
        bands = len(c.assets) + len(c.optional)
        lines.append(f"| `{name}` | {c.kind} | {bands} | " + " | ".join(cell(name, a) for a in archives) + " |")
    return "\n".join(lines)


def updated(text: str) -> str:
    """The document with the table between its markers replaced."""
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{table()}\n{END}{tail}"


def main(argv: list[str]) -> int:
    text = DOC.read_text()
    new = updated(text)
    if "--check" in argv:
        if new != text:
            print(f"{DOC} is out of date: run python -m majortom.build.catalogue", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(new)
    print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
